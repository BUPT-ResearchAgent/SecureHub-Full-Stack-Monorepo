type QuestionBase = {
  id: string;
  paperId: string;
  order: number;
  knowledgePointId: string;
  difficulty: 1 | 2 | 3 | 4 | 5;
  points: number;
  stem: string;
  explanation: string;
  relatedResourceIds: readonly string[];
};

function option(id: string, text: string): WebSecurityQuestionOption {
  return { id, text };
}

function single(
  input: QuestionBase & { options: readonly WebSecurityQuestionOption[]; correctOptionId: string; answerText: string },
): WebSecurityQuestion {
  const { correctOptionId, answerText, ...question } = input;
  return {
    ...questionMetadata,
    ...question,
    type: 'single_choice',
    answer: { kind: 'option', optionIds: [correctOptionId], display: answerText },
    scoring: { mode: 'single_exact', correctOptionIds: [correctOptionId] },
  };
}

function multi(
  input: QuestionBase & { options: readonly WebSecurityQuestionOption[]; correctOptionIds: readonly string[]; answerText: string },
): WebSecurityQuestion {
  const { correctOptionIds, answerText, ...question } = input;
  return {
    ...questionMetadata,
    ...question,
    type: 'multi_choice',
    answer: { kind: 'option', optionIds: correctOptionIds, display: answerText },
    scoring: { mode: 'multi_exact', correctOptionIds },
  };
}

function fill(input: QuestionBase & { acceptedAnswers: readonly string[]; answerText: string }): WebSecurityQuestion {
  const { acceptedAnswers, answerText, ...question } = input;
  return {
    ...questionMetadata,
    ...question,
    type: 'fill',
    answer: { kind: 'fill', acceptedAnswers, display: answerText },
    scoring: { mode: 'fill_normalized', acceptedAnswers },
  };
}

function rubric(
  input: QuestionBase & {
    type: 'short_answer' | 'code';
    rubric: readonly WebSecurityRubricCriterion[];
    exemplarAnswer: string;
  },
): WebSecurityQuestion {
  const { rubric: criteria, exemplarAnswer, ...question } = input;
  return {
    ...questionMetadata,
    ...question,
    answer: { kind: 'rubric', exemplarAnswer, display: exemplarAnswer },
    scoring: { mode: 'rubric_self_check', rubric: criteria },
  };
}

